inline int& hydroLstmSequenceLengthRuntimeDefault() {
    static int value = 6;
    return value;
}

struct HydroScalerState {
    std::string method = "none";
    std::vector<double> offset = {0.0};
    std::vector<double> scale = {1.0};
    std::vector<int64_t> shape = {1};
};

struct HydroRunConfig {
    int epochs = 150;
    int batch_size = 32;
    double learning_rate = 0.003;

    // PINN-specific options.
    // Physics profiles:
    // - linear_reservoir: single linear-reservoir routing constraint
    //       dQ/dt = k(I*-Q),  k = 1/K,
    //   with I*=max(P-PET,0). This remains the controlled reduced-physics
    //   benchmark and synthetic known-truth verification path.
    // - two_reservoir_hybrid: process-aware LSTM+PINN for real catchments.
    //   The recurrent network learns non-negative effective runoff generation
    //   R_nn from meteorological sequences and differentiable fast/slow routing
    //   imposes
    //       dQ_f/dt = k_f(alpha R_nn-Q_f),
    //       dQ_s/dt = k_s((1-alpha)R_nn-Q_s), Q=Q_f+Q_s.
    //   For this profile storage_coeff=k_f, lambda_decay=k_s, runoff_coeff=alpha.
    //   Neural inputs/targets are standardized using training data only while
    //   routing and physical diagnostics remain in physical units.
    // - water_balance: explicit known-state balance P-ET-Q-dS/dt=0; intended for
    //   controlled synthetic or packages that independently provide storage S.
    // - cstr_first_order: dy/dt + lambda*y - forcing_gain*u = 0.
    // - exp_decay: dy/dt + lambda*y = 0.
    double lambda_decay = 0.8;
    double data_weight = 1.0;
    double physics_weight = 0.2;
    std::string pinn_physics_profile = "water_balance";
    double forcing_gain = 1.0;
    double runoff_coeff = 0.7;
    double storage_coeff = 1.0;
    double physics_dt = 1.0;
    int pinn_collocation_points = 0;
    // pinn_two_reservoir_hybrid only: delays the forcing series feeding the
    // reservoir routing by this many hours, to correct a systematic
    // catchment travel-time lag between rainfall and gauge response that the
    // reservoirs' own K-based dynamics do not otherwise capture.
    double pinn_routing_lag_hours = 0.0;
    // pinn_two_reservoir_hybrid only: makes both reservoirs' rate constants
    // scale with (current_flow/initial_flow)^pinn_flow_exponent instead of
    // being fixed, so effective travel time varies by event instead of being
    // frozen to one value. 0.0 (default) recovers the original constant-K
    // behavior exactly.
    double pinn_flow_exponent = 0.0;

    // Historical flag name retained for experiment compatibility. For GIStoOHQ
    // reduced-reservoir and process-aware physics it selects the contiguous
    // forcing-only layout; no latent storage is generated by the data builder.
    bool use_latent_storage_physics = false;
    double latent_storage_recession_per_hour = 0.08;

    bool use_csv_data = false;
    bool use_hydro_package = false;
    std::string hydro_package_path;
    std::string hydro_catchment_id;
    std::string hydro_package_profile = "rainfall-runoff";
    bool use_hydro_forecast_feature = false;
    std::string hydro_forecast_variable = "precipitation";
    double hydro_forecast_lead_hours = 0.0;
    std::string hydro_forecast_ensemble_member;
    std::string csv_path;
    int csv_x_column = 0;
    int csv_y_column = 1;
    bool csv_has_header = true;

    int sample_count = 220;
    double t_start = 0.0;
    double t_end = 5.0;
    std::string synthetic_profile = "watershed_balance";
    double synthetic_reservoir_truth_k = 0.08;

    std::string hidden_layers_csv = "24,24";
    std::string input_lags_csv = "1";
    bool use_time_lagged_ffn = false;
    int lstm_sequence_length = hydroLstmSequenceLengthRuntimeDefault();
    std::string activation = "tanh";

    bool evaluate_metrics = true;
    double train_split_ratio = 0.8;
    double validation_split_ratio = 0.1;
    // Optional: bounds the test partition's end as a fraction of total rows,
    // instead of letting it run to the literal end of the loaded series -
    // see chronological_split.h's makeChronologicalSplit doc comment for why
    // this exists. -1.0 (default) = unbounded, identical to this field never
    // having existed. Prefer test_end_x below when the exact row index is
    // known: this ratio-based field was found to silently land at a
    // different absolute row per model family (different input-sequence
    // lengths consume different warm-up row counts for the same `total`),
    // which caused a validation-row-contamination bug in the Sligo Creek
    // program - see chronological_split.h's doc comment on testEndX.
    double test_end_split_ratio = -1.0;
    // Optional: bounds the test partition's end at an exact x coordinate,
    // taking priority over test_end_split_ratio when both are set. -1
    // (default) = unset. Prefer this over the ratio field whenever the
    // caller knows the exact intended bound (e.g. a named flood window's
    // end) - see chronological_split.h's testEndX doc comment.
    //
    // IMPORTANT: this value is in the same exported-x coordinate space as
    // predictions.csv's own "x" column (the canonical, gap-aware hour-index
    // convention used throughout this program, see seal_guard.py) - NOT a
    // raw sequence-index or array position. A windowed sequence builder
    // (LSTM, LSTM-PINN) skips windows across a time/segment gap, and even a
    // non-windowed model's raw tensor can have upstream-filtered gaps, so
    // array position is not the same as x. Every wrapper must resolve this
    // value against its own actual per-sequence/per-row endpoint x values
    // via resolve_test_end_x.h's resolveTestEndSequenceCount() BEFORE
    // passing the result to makeChronologicalSplit - never pass this field
    // straight through. Confirmed necessary directly: a first attempt at
    // this feature passed it straight through for one model family and
    // produced a test partition 951 x-units longer than intended, traced to
    // 928 x-units of cumulative drift from 8 time gaps earlier in the
    // series - see
    // results/nse08_recovery_20261015/phase3_regional/00_phase3_design.md's
    // "Status update" section for the full account.
    int64_t test_end_x = -1;
    bool shuffle_training = true;
    int random_seed = 42;
    std::string optimizer = "adam";
    double weight_decay = 0.0;
    double momentum = 0.9;
    std::string normalization = "none";

    bool use_incremental_training = false;
    double window_size = 1.0;
    double window_step = 0.5;
    int epochs_per_window = 25;
    bool reset_optimizer_on_new_window = false;

    // LSTM/LSTM+PINN only: adds weight*(mean(pred)-mean(observed))^2 on the
    // physical (inverse-scaled) discharge to each mini-batch's loss, directly
    // penalizing systematic volume bias (what PBIAS measures) instead of only
    // pointwise MSE, which does not penalize a consistent over/under-shoot as
    // long as pointwise error stays low. 0.0 (default) recovers prior
    // behavior exactly.
    double lstm_bias_weight = 0.0;

    // FFN residual hybrid only: when true, lstm_bias_weight is used only as
    // the *initial* bias-penalty weight; the actual weight becomes a learned
    // parameter (Kendall et al. 2017 homoscedastic uncertainty weighting: a
    // log-variance scalar, trained jointly with the network by the same
    // optimizer) instead of a fixed constant. Motivated by the bias-penalty
    // scale probe (results/residual_hybrid_bias_penalty_20261008) needing a
    // manual search across weights 10/100/1000 with high seed-to-seed
    // variance in how well any single fixed weight worked. false (default)
    // recovers prior fixed-weight behavior exactly.
    bool lstm_bias_weight_adaptive = false;

    // FFN residual hybrid and plain LSTM: adds
    // weight*mean(((pred_physical-observed_physical)/train_discharge_std)^2)
    // to each mini-batch's loss, alongside (not replacing) the existing
    // transformed-space loss (asinh-residual for the hybrid, log1p for the
    // LSTM). Motivated by a loss/gradient-contribution audit
    // (results/precipitation_unit_fix_20261012/) finding that the
    // transformed-space loss under-weights flood hours relative to their
    // true physical error: flood peak hours were ~0.04% of training hours
    // but ~64-70% of total physical squared error, yet only ~20-30% of
    // total transformed-space loss mass - a real, measured compression
    // effect (not total suppression: floods were not literally ignored).
    // The physical term is normalized by the training split's own
    // discharge standard deviation (fit on train only, like every other
    // scaler in this project) so it is commensurate with the standardized
    // transformed-space term rather than dominating by raw mm/h scale.
    // Deliberately unweighted (1.0) when enabled, not swept, to isolate
    // "does adding this term help at all" from "what weight is optimal" -
    // the latter is a separate question. 0.0 (default) recovers prior
    // behavior exactly.
    double physical_error_weight = 0.0;

    // Plain LSTM only: inter-layer dropout passed to torch::nn::LSTMOptions.
    // Only has an effect when hidden_layers specifies 2+ layers (torch does
    // not apply dropout after the last layer). 0.0 (default) recovers prior
    // behavior exactly.
    double lstm_dropout = 0.0;

    // Plain LSTM only: if non-empty, loads this checkpoint file (same .pt
    // format HydroBatch already exports to <output>/models/<approach>.pt)
    // as the model's initial weights instead of random initialization -
    // a warm start, for staged coarse-to-fine temporal-resolution training
    // (e.g. pretrain on monthly data, warm-start on daily, warm-start on
    // hourly). Architecture (hidden_layers, input/output dims) must match
    // the checkpoint's; only has an effect when input_lags/features and the
    // resulting tensor shapes are identical across stages - this project's
    // 6-column forcing contract is unchanged across temporal resolutions, so
    // shapes are compatible, but what an LSTM "step" represents differs
    // between resolutions. "" (default) recovers random initialization.
    std::string lstm_warm_start_checkpoint_path = "";

    // Plain LSTM only: appends an Antecedent Precipitation Index column
    // (API_t = k*API_{t-1} + Peff_t, k chosen so API decays to half its
    // value after this many hours) as an extra input feature, giving the
    // network an explicit long-memory wetness signal beyond whatever its
    // own recurrence/lookback window already sees. 0.0 (default) disables
    // this and recovers prior behavior exactly.
    double antecedent_index_halflife_hours = 0.0;

    // Regional multi-basin pretraining mode only (lstm_regional_pretrain,
    // see lstm_regional_pretrain.h): paths to plain text files, one
    // GIStoOHQ package directory per line, listing the basins pooled for
    // training and the basins entirely held out for checkpoint-selection
    // validation respectively - the same one-per-line convention already
    // used by urban_tier.txt/all_candidates.txt, not a JSON array (this
    // config format has no array support). "" (default) disables this mode.
    std::string regional_training_basin_list_path = "";
    std::string regional_validation_basin_list_path = "";
    // <= 0 (default) means "auto" - see RegionalPretrainConfig's doc
    // comment in lstm_regional_pretrain.h for what auto picks.
    int64_t regional_per_basin_sequence_count = -1;
    // Optional exact calendar window [start, end) applied to EVERY basin
    // (training and validation alike) before sequencing - UTC ISO8601
    // "YYYY-MM-DDTHH:MM:SSZ". "" (default, either field) = unbounded, i.e.
    // every row the package contains is used, identical to this field
    // never having existed. Required for this program's pilot manifest
    // (2015-01-01 through 2022-12-31 inclusive): CAMELSH-ingested packages
    // span 1980 through the 2023-10-15 seal, far more than the declared
    // pretraining window, and loadHydroPackageTensors has no date-range
    // concept of its own - confirmed as a real gap (not just a theoretical
    // one) when a first pilot attempt silently loaded every available row
    // instead of the declared window. See regional_window_filter.h.
    std::string regional_window_start = "";
    std::string regional_window_end = "";
};

