"""Small, exact active-face solver for a bounded causal routing hypothesis.

Forecast = past_gain * dry_forecast + storm_gain * (held_forecast-dry_forecast)
           + background_mm_h.
The background is an explicit empirical source, not water generated by the
reservoir ledger. All coefficients must be frozen from training observations.
"""
import itertools
import numpy as np


def box_least_squares(design, target, upper):
    x=np.asarray(design,dtype=float);y=np.asarray(target,dtype=float);u=np.asarray(upper,dtype=float)
    if x.ndim!=2 or y.ndim!=1 or len(y)!=len(x) or x.shape[1]!=len(u) or not 1<=len(u)<=3:
        raise ValueError('Invalid fitting shapes')
    if not np.isfinite(x).all() or not np.isfinite(y).all() or not np.isfinite(u).all() or (x<0).any() or (y<0).any() or (u<=0).any():
        raise ValueError('Invalid fitting domain')
    # Scale all unknowns to [0,1]. Enumerate every face of this <=3-D box;
    # constrained convex least squares has an optimum on one of these faces.
    a=x*u;best=None
    for states in itertools.product((0,1,2),repeat=len(u)): # lower,free,upper
        z=np.array([1. if s==2 else 0. for s in states]);free=[i for i,s in enumerate(states) if s==1]
        if free:
            z[free]=np.linalg.lstsq(a[:,free],y-a@z,rcond=None)[0]
            if np.any(z[free]<-1e-10) or np.any(z[free]>1+1e-10):continue
            z=np.clip(z,0,1)
        residual=a@z-y;loss=float(residual@residual)
        if best is None or loss<best[0]:best=(loss,z*u)
    if best is None:raise RuntimeError('No feasible face')
    return best[1]


def component_design(dry,wet,background=False):
    dry=np.asarray(dry,dtype=float);wet=np.asarray(wet,dtype=float)
    if dry.shape!=wet.shape or dry.ndim!=1 or not np.isfinite(dry).all() or not np.isfinite(wet).all() or (dry<0).any() or (wet<0).any():
        raise ValueError('Invalid component vectors')
    increment=wet-dry
    if (increment < -1e-10).any():raise ValueError('Held rain reduced outflow')
    columns=[dry,np.maximum(0,increment)]
    if background:columns.append(np.ones_like(dry))
    return np.column_stack(columns)
